    "import os\n",
    "import cv2\n",
    "import numpy as np\n",
    "from typing import Tuple, Optional\n",
    "\n",
    "\n",
    "def preprocess_for_training(\n",
    "    img: np.ndarray,\n",
    "    target_size: Tuple[int, int] = (224, 224),\n",
    "    color_mode: str = \"RGB\",\n",
    "    crop_center: Optional[Tuple[int, int]] = None,\n",
    "    normalize: bool = True\n",
    ") -> np.ndarray:\n",
    "    \"\"\"\n",
    "    Basic preprocessing pipeline for training images.\n",
    "\n",
    "    Steps:\n",
    "    1. Optional cropping (center crop).\n",
    "    2. Resize to target size.\n",
    "    3. Convert color space (BGR → RGB/GRAY).\n",
    "    4. Normalize pixel values to [0, 1].\n",
    "\n",
    "    Parameters\n",
    "    ----------\n",
    "    img : np.ndarray : Image read using cv2.imread() in BGR format.\n",
    "    target_size : tuple : (width, height)\n",
    "    color_mode : \"RGB\", \"BGR\", or \"GRAY\"\n",
    "    crop_center : (crop_h, crop_w) or None : Optional center crop\n",
    "    normalize : bool : If True, scale values to [0, 1]\n",
    "\n",
    "    Returns\n",
    "    -------\n",
    "    np.ndarray\n",
    "    \"\"\"\n",
    "\n",
    "    # 1️⃣ Center crop (optional)\n",
    "    if crop_center is not None:\n",
    "        crop_h, crop_w = crop_center\n",
    "        h, w = img.shape[:2]\n",
    "\n",
    "        crop_h = min(crop_h, h)\n",
    "        crop_w = min(crop_w, w)\n",
    "\n",
    "        start_y = (h - crop_h) // 2\n",
    "        start_x = (w - crop_w) // 2\n",
    "        img = img[start_y:start_y + crop_h, start_x:start_x + crop_w]\n",
    "\n",
    "    # 2️⃣ Resize image\n",
    "    target_w, target_h = target_size\n",
    "    img = cv2.resize(img, (target_w, target_h), interpolation=cv2.INTER_AREA)\n",
    "\n",
    "    # 3️⃣ Convert color format\n",
    "    if color_mode.upper() == \"RGB\":\n",
    "        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)\n",
    "    elif color_mode.upper() == \"GRAY\":\n",
    "        img = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)\n",
    "\n",
    "    # 4️⃣ Normalize\n",
    "    if normalize:\n",
    "        img = img.astype(np.float32) / 255.0\n",
    "\n",
    "    return img\n",
    "\n",
    "\n",
    "def process_dataset_folder(\n",
    "    input_root: str,\n",
    "    output_root: str,\n",
    "    target_size: Tuple[int, int] = (224, 224),\n",
    "    color_mode: str = \"RGB\",\n",
    "    crop_center: Optional[Tuple[int, int]] = None,\n",
    "    normalize: bool = True,\n",
    "    save_as: str = \"png\"\n",
    "):\n",
    "    \"\"\"\n",
    "    Preprocess all images in dataset folder structure:\n",
    "    input_root/class_name/*.jpg\n",
    "\n",
    "    Saves processed images in identical class structure inside output_root\n",
    "    \"\"\"\n",
    "\n",
    "    os.makedirs(output_root, exist_ok=True)\n",
    "\n",
    "    for class_name in os.listdir(input_root):\n",
    "        class_in = os.path.join(input_root, class_name)\n",
    "        class_out = os.path.join(output_root, class_name)\n",
    "\n",
    "        if not os.path.isdir(class_in):\n",
    "            continue\n",
    "\n",
    "        os.makedirs(class_out, exist_ok=True)\n",
    "\n",
    "        for fname in os.listdir(class_in):\n",
    "            in_path = os.path.join(class_in, fname)\n",
    "\n",
    "            if not os.path.isfile(in_path):\n",
    "                continue\n",
    "\n",
    "            if not fname.lower().endswith((\".png\", \".jpg\", \".jpeg\", \".bmp\", \".tif\", \".tiff\")):\n",
    "                continue\n",
    "\n",
    "            img = cv2.imread(in_path)\n",
    "            if img is None:\n",
    "                print(f\"⚠️ Skipping unreadable: {in_path}\")\n",
    "                continue\n",
    "\n",
    "            processed = preprocess_for_training(\n",
    "                img,\n",
    "                target_size=target_size,\n",
    "                color_mode=color_mode,\n",
    "                crop_center=crop_center,\n",
    "                normalize=normalize\n",
    "            )\n",
    "\n",
    "            save_img = processed\n",
    "            if normalize:\n",
    "                save_img = (processed * 255.0).clip(0, 255).astype(np.uint8)\n",
    "\n",
    "            if color_mode.upper() == \"RGB\":\n",
    "                save_img = cv2.cvtColor(save_img, cv2.COLOR_RGB2BGR)\n",
    "\n",
    "            out_path = os.path.join(class_out, f\"{os.path.splitext(fname)[0]}.{save_as}\")\n",
    "            cv2.imwrite(out_path, save_img)\n",
    "\n",
    "        print(f\"✔ Processed class: {class_name}\")\n",
    "\n",
    "\n",
    "if __name__ == \"__main__\":\n",
    "    print(\"Running preprocessing directly...\")\n",
    "    process_dataset_folder(\n",
    "        input_root=\"data\",\n",
    "        output_root=\"processed_images\"\n",
    "    )\n",
    "    print(\"Done! 🎯\")\n"
